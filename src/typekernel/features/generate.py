"""Naming-suffix → OpenType feature text (target-architecture §11.1)."""

from __future__ import annotations

import re
from collections import defaultdict
from collections.abc import Mapping, Sequence
from typing import Any

__all__ = ["generate_cursive_features", "generate_features", "parse_suffix"]

_SS = re.compile(r"^(.+)\.ss(\d{2})$")
_CV = re.compile(r"^(.+)\.cv(\d{2})$")
_SC = re.compile(r"^(.+)\.sc$")
_CASE = re.compile(r"^(.+)\.case$")
_TF = re.compile(r"^(.+)\.tf$")
_LF = re.compile(r"^(.+)\.lf$")
_OSF = re.compile(r"^(.+)\.osf$")
_TOSF = re.compile(r"^(.+)\.tosf$")
_ALT = re.compile(r"^(.+)\.alt(\d*)$")
_DLIG = re.compile(r"\.dlig$")
_INIT = re.compile(r"^(.+)\.init$")
_MEDI = re.compile(r"^(.+)\.medi$")
_FINA = re.compile(r"^(.+)\.fina$")
_ISOL = re.compile(r"^(.+)\.isol$")


def parse_suffix(name: str) -> tuple[str, str, str] | None:
    """Return ``(kind, feature_tag, base)`` or None if name is not a variant."""
    m = _SS.match(name)
    if m:
        return ("sub", f"ss{m.group(2)}", m.group(1))
    m = _CV.match(name)
    if m:
        return ("sub", f"cv{m.group(2)}", m.group(1))
    if _SC.match(name):
        base = name[: -len(".sc")]
        if base and base[0].isupper() and base.isalpha():
            return ("sub", "c2sc", base)
        return ("sub", "smcp", base)
    if _CASE.match(name):
        return ("sub", "case", name[: -len(".case")])
    if _TF.match(name):
        return ("sub", "tnum", name[: -len(".tf")])
    if _LF.match(name):
        return ("sub", "lnum", name[: -len(".lf")])
    if _OSF.match(name):
        return ("sub", "onum", name[: -len(".osf")])
    if _TOSF.match(name):
        return ("sub", "tosf", name[: -len(".tosf")])
    m = _ALT.match(name)
    if m:
        return ("sub", "salt", m.group(1))
    m = _INIT.match(name)
    if m:
        return ("pos", "calt", m.group(1))
    m = _MEDI.match(name)
    if m:
        return ("pos", "calt", m.group(1))
    m = _FINA.match(name)
    if m:
        return ("pos", "calt", m.group(1))
    m = _ISOL.match(name)
    if m:
        return ("pos", "calt", m.group(1))
    if "_" in name and not name.startswith("_"):
        core = _DLIG.sub("", name)
        parts = core.split("_")
        if len(parts) >= 2 and all(p.isalnum() for p in parts):
            tag = "dlig" if name.endswith(".dlig") else "liga"
            return ("liga", tag, name)
    return None


def generate_features(glyph_names: set[str] | frozenset[str] | list[str]) -> str:
    """Emit AFDKO feature file text for suffix-named glyphs present in the set."""
    names = set(glyph_names)
    by_feat: dict[str, list[tuple[str, str]]] = defaultdict(list)
    ligas: dict[str, list[tuple[str, list[str]]]] = defaultdict(list)
    aalt_pairs: list[tuple[str, str]] = []
    positional: dict[str, dict[str, str]] = defaultdict(dict)

    for name in sorted(names):
        parsed = parse_suffix(name)
        if parsed is None:
            continue
        kind, tag, base = parsed
        if kind == "pos":
            form = name.rsplit(".", 1)[-1]
            if base in names:
                positional[base][form] = name
            continue
        if kind == "liga":
            core = _DLIG.sub("", name)
            parts = core.split("_")
            if all(p in names for p in parts):
                ligas[tag].append((name, parts))
            continue
        if tag == "tosf":
            if base in names:
                by_feat["onum"].append((base, name))
                by_feat["tnum"].append((base, name))
                aalt_pairs.append((base, name))
            continue
        if base not in names:
            continue
        by_feat[tag].append((base, name))
        if tag.startswith(("ss", "cv")) or tag in {"salt", "case"}:
            aalt_pairs.append((base, name))

    chunks: list[str] = ["# Auto-generated by typekernel.features.generate_features", ""]
    order = sorted(
        by_feat.keys(),
        key=lambda t: (0 if t.startswith("ss") else 1 if t.startswith("cv") else 2, t),
    )
    for tag in order:
        pairs = by_feat[tag]
        if not pairs:
            continue
        chunks.append(f"feature {tag} {{")
        for base, alt in pairs:
            chunks.append(f"  sub {base} by {alt};")
        chunks.append(f"}} {tag};")
        chunks.append("")

    for tag, items in sorted(ligas.items()):
        chunks.append(f"feature {tag} {{")
        for liga_name, parts in items:
            chunks.append(f"  sub {' '.join(parts)} by {liga_name};")
        chunks.append(f"}} {tag};")
        chunks.append("")

    if aalt_pairs:
        chunks.append("feature aalt {")
        for base, alt in aalt_pairs:
            chunks.append(f"  sub {base} from [{base} {alt}];")
        chunks.append("} aalt;")
        chunks.append("")

    if positional:
        # Practical calt: expose positional swaps; engines pick by context later.
        chunks.append("feature calt {")
        chunks.append("  # S3 positional forms (.init / .medi / .fina / .isol)")
        for base in sorted(positional):
            forms = positional[base]
            for form in ("isol", "init", "medi", "fina"):
                alt_name = forms.get(form)
                if alt_name is not None:
                    chunks.append(f"  sub {base} by {alt_name};")
        chunks.append("} calt;")
        chunks.append("")

    return "\n".join(chunks).rstrip() + "\n"


def generate_cursive_features(
    glyph_anchors: Mapping[str, Sequence[Any]],
) -> str:
    """Emit ``curs`` GPOS cursive attachment from entry/exit anchors."""
    rows: list[str] = []
    for gname in sorted(glyph_anchors):
        by: dict[str | None, Any] = {getattr(a, "name", None): a for a in glyph_anchors[gname]}
        entry = by.get("entry")
        exit_a = by.get("exit")
        if entry is None or exit_a is None:
            continue
        rows.append(
            f"  pos cursive {gname} "
            f"<anchor {float(exit_a.x):g} {float(exit_a.y):g}> "
            f"<anchor {float(entry.x):g} {float(entry.y):g}>;"
        )
    if not rows:
        return ""
    return "\n".join(
        [
            "# S3 cursive attachment (exit then entry)",
            "feature curs {",
            *rows,
            "} curs;",
            "",
        ]
    )
